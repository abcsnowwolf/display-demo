#!/usr/bin/env python3
"""Subset the upstream CJK fonts down to what the device needs.

Requires fontTools (pip install fonttools). Usage:

    python3 tools/subset_fonts.py <download_dir> [output names...]

<download_dir> must contain the upstream files listed in SOURCES (see
README.md for download links). Subset fonts are written to fonts/, which is
what tools/build_fonts.py packs into the flash font partition.
"""
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "fonts")

# (source file, output file, character set)
SOURCES = [
    ("NotoSansSC-Regular.otf", "sans.otf", "text"),
    ("NotoSansSC-Bold.otf", "sans-bold.otf", "text"),
    ("LXGWWenKai-Regular.ttf", "kai.ttf", "text"),
    ("SmileySans-Oblique.otf", "display.otf", "text"),
    ("MaterialIconsRound-Regular.otf", "icons.otf", "icons"),
    ("Twemoji.Mozilla.ttf", "emoji.ttf", "emoji"),
]

ICON_CODEPOINTS = "MaterialIconsRound-Regular.codepoints"


def text_charset():
    """GB2312 (all 6763 hanzi + symbols) plus Latin and common punctuation."""
    chars = set()
    for hi in range(0xA1, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                chars.add(bytes([hi, lo]).decode("gb2312"))
            except UnicodeDecodeError:
                pass
    ranges = [
        (0x20, 0x7E),      # ASCII
        (0xA0, 0xFF),      # Latin-1 supplement
        (0x2010, 0x205E),  # general punctuation
        (0x2070, 0x209F),  # super/subscripts (CO₂ m²)
        (0x2100, 0x215F),  # letterlike symbols (℃ № ™)
        (0x2190, 0x21FF),  # arrows
        (0x2460, 0x24FF),  # enclosed alphanumerics (① ②)
        (0x2500, 0x257F),  # box drawing
        (0x25A0, 0x25FF),  # geometric shapes
        (0x2600, 0x26FF),  # misc symbols (☀ ★ ☑)
        (0x2700, 0x27BF),  # dingbats (✓ ✗)
        (0x3000, 0x303F),  # CJK punctuation
        (0xFF00, 0xFFEF),  # full-width forms
    ]
    for lo, hi in ranges:
        chars.update(chr(c) for c in range(lo, hi + 1))
    # Common characters outside GB2312 that show up in modern text.
    chars.update("啰喆堃嫚昇氹犇珺琊琍瑄瑢甦祎禛筠缐翀翯镕婷玥炜昊晗旻钰祺瑾琪")
    return "".join(sorted(chars))


def emoji_codepoints(font):
    """Single-codepoint emoji only: the device does no shaping, so ZWJ
    sequences, keycaps, flags-by-ligature and skin-tone variants (all GSUB)
    are dropped. ASCII (keycap bases) and modifier/selector codepoints go too."""
    skip = set(range(0x1F3FB, 0x1F400)) | {0x200D, 0x20E3, 0xFE0F}
    return [cp for cp in font.getBestCmap() if cp >= 0xA0 and cp < 0xE0000 and cp not in skip]


def icon_names(download_dir):
    names = {}
    with open(os.path.join(download_dir, ICON_CODEPOINTS)) as f:
        for line in f:
            name, cp = line.split()
            names[name] = int(cp, 16)
    return names


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    src_dir = sys.argv[1]
    only = set(sys.argv[2:])  # e.g. "emoji.ttf" to redo just one font
    os.makedirs(OUT_DIR, exist_ok=True)

    # The icon set is curated: the full Material Icons font has ~2000 glyphs,
    # but the device only advertises the names listed in fonts/icons.txt.
    icons = not only or "icons.otf" in only
    if icons:
        with open(os.path.join(OUT_DIR, "icons.txt")) as f:
            wanted = [l.strip() for l in f if l.strip() and not l.startswith("#")]
        all_icons = icon_names(src_dir)
        missing = [n for n in wanted if n not in all_icons]
        if missing:
            sys.exit("unknown icon names: " + ", ".join(missing))

    for src, dst, charset in SOURCES:
        if only and dst not in only:
            continue
        opts = subset.Options()
        opts.hinting = False
        opts.desubroutinize = False
        opts.layout_features = ["kern"]
        # Subsets are Modified Versions under the OFL and may not carry the
        # Reserved Font Names (LXGW, Smiley/得意黑), so drop the name table
        # records entirely; the rasterizer does not need them.
        opts.name_IDs = []
        opts.notdef_outline = True
        opts.glyph_names = False
        font = TTFont(os.path.join(src_dir, src))
        sub = subset.Subsetter(opts)
        if charset == "icons":
            sub.populate(unicodes=[all_icons[n] for n in wanted])
        elif charset == "emoji":
            opts.layout_features = []  # COLR/CPAL are kept; GSUB ligatures are not used
            sub = subset.Subsetter(opts)
            sub.populate(unicodes=emoji_codepoints(font))
        else:
            sub.populate(text=text_charset())
        sub.subset(font)
        out = os.path.join(OUT_DIR, dst)
        font.save(out)
        print(f"{dst:16s} {os.path.getsize(out) / 1024:8.0f} KiB")

    if not icons:
        return
    # Name -> codepoint table compiled into the firmware.
    with open(os.path.join(ROOT, "src", "gfx", "IconNames.inc"), "w") as f:
        f.write("// Generated by tools/subset_fonts.py from fonts/icons.txt. Do not edit.\n")
        for name in sorted(wanted):
            f.write(f'{{"{name}", 0x{all_icons[name]:04X}}},\n')


if __name__ == "__main__":
    main()
